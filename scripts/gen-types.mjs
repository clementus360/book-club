// Generates src/lib/database.types.ts from the migrations, in the shape
// supabase-js expects. Run with `npm run db:types` after changing a migration.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import pg from "pg";
import { createDatabase, startPostgres } from "../tests/support/postgres.mjs";

const server = await startPostgres();
const db = new pg.Client({ connectionString: await createDatabase(server.url, "gen_types") });
await db.connect();
const q = async (text) => (await db.query(text)).rows;

const enums = await q(`select t.typname name, array_agg(e.enumlabel::text order by e.enumsortorder) labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid where t.typnamespace = 'public'::regnamespace group by 1 order by 1`);
const enumNames = new Set(enums.map((e) => e.name));
const tables = new Set((await q(`select relname from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r'`)).map((r) => r.relname));
const ts = (type) => {
  if (type.startsWith("_")) return `${ts(type.slice(1))}[]`;
  if (enumNames.has(type)) return `Database["public"]["Enums"]["${type}"]`;
  if (tables.has(type)) return `Database["public"]["Tables"]["${type}"]["Row"]`;
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(type)) return "number";
  if (type === "bool") return "boolean";
  if (["json", "jsonb"].includes(type)) return "Json";
  if (type === "void") return "undefined";
  return "string";
};
const columns = await q(`select table_name, column_name, udt_name, is_nullable = 'YES' nullable, column_default is not null has_default
  from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`);
const fks = await q(`select c.conname name, c.conrelid::regclass::text tbl, c.confrelid::regclass::text ref,
    (select array_agg(a.attname::text order by k.ord) from unnest(c.conkey) with ordinality k(n, ord) join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.n) cols,
    (select array_agg(a.attname::text order by k.ord) from unnest(c.confkey) with ordinality k(n, ord) join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.n) refcols
  from pg_constraint c where c.contype = 'f' and c.connamespace = 'public'::regnamespace and c.confrelid in (select oid from pg_class where relnamespace = 'public'::regnamespace) order by 1`);
const fns = await q(`select p.proname name, p.proretset setof, p.pronargdefaults ndef, p.proargnames argnames, p.proargmodes::text[] modes,
    array(select t.typname::text from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality x(o, n) join pg_type t on t.oid = x.o order by x.n) types,
    r.typname ret from pg_proc p join pg_type r on r.oid = p.prorettype where p.pronamespace = 'public'::regnamespace order by 1`);

let out = `// Generated by scripts/gen-types.mjs from supabase/migrations. Do not edit.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {\n`;
for (const table of [...tables].sort()) {
  const cols = columns.filter((c) => c.table_name === table);
  const line = (c, opt) => `          ${c.column_name}${opt ? "?" : ""}: ${ts(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  out += `      ${table}: {\n        Row: {\n${cols.map((c) => line(c, false)).join("")}        };\n`;
  out += `        Insert: {\n${cols.map((c) => line(c, c.nullable || c.has_default)).join("")}        };\n`;
  out += `        Update: {\n${cols.map((c) => line(c, true)).join("")}        };\n        Relationships: [\n`;
  for (const f of fks.filter((f) => f.tbl.replace("public.", "") === table)) {
    out += `          { foreignKeyName: "${f.name}"; columns: ${JSON.stringify(f.cols)}; isOneToOne: false; referencedRelation: "${f.ref.replace("public.", "")}"; referencedColumns: ${JSON.stringify(f.refcols)} },\n`;
  }
  out += `        ];\n      };\n`;
}
out += `    };\n    Views: { [_ in never]: never };\n    Functions: {\n`;
for (const f of fns) {
  const modes = f.modes ?? f.types.map(() => "i");
  const ins = f.types.map((t, i) => ({ t, name: f.argnames?.[i], mode: modes[i] })).filter((a) => a.mode === "i");
  const outs = f.types.map((t, i) => ({ t, name: f.argnames?.[i], mode: modes[i] })).filter((a) => a.mode === "t");
  const args = ins.map((a, i) => `${a.name}${i >= ins.length - f.ndef ? "?" : ""}: ${ts(a.t)}${["text", "int2", "timestamptz"].includes(a.t) ? " | null" : ""}`).join("; ");
  const ret = outs.length ? `{ ${outs.map((o) => `${o.name}: ${ts(o.t)}`).join("; ")} }[]` : `${ts(f.ret)}${f.setof ? "[]" : ""}`;
  out += `      ${f.name}: { Args: ${args ? `{ ${args} }` : "Record<PropertyKey, never>"}; Returns: ${ret} };\n`;
}
out += `    };\n    Enums: {\n${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};\n`).join("")}    };\n    CompositeTypes: { [_ in never]: never };\n  };\n};

export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];
export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];
`;
writeFileSync(fileURLToPath(new URL("../src/lib/database.types.ts", import.meta.url)), out);
await db.end();
server.stop();
console.log(`Wrote types for ${tables.size} tables and ${fns.length} functions.`);
